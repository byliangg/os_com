//! Real-Linux multi-descriptor journal vectors (P7a-5 gate 3).
//!
//! Pinned VERBATIM from a dirty jbd2 journal written by Linux 6.8 on a
//! 512 MiB `mke2fs 1.47 -t ext4 -b 4096 -O metadata_csum,64bit` image
//! pre-populated with 6000 files: mounted `-o commit=99999`, a `chmod -R` +
//! `mv` sweep over everything accumulated one running transaction touching
//! 381 metadata blocks, and `syncfs` committed it as a REAL two-descriptor
//! chain (Linux seals a descriptor early when its conservative space check
//! trips, so descriptor #1 carries 253 tags, not the 254 the tag area
//! holds). `debugfs logdump` and an independent byte-level parse both
//! confirmed the chain, and every checksum (superblock, both descriptor
//! tails, all 381 tag data checksums, the commit block) reproduces under
//! our formulas seeded from the journal UUID.
//!
//! Only the CHAIN blocks are pinned — the two descriptors and the commit
//! block. The 381 logged data blocks are not (they would pin ~1.5 MiB, and
//! their destinations exceed any ktest fixture disk), so these vectors
//! feed the SCAN side (which reads no data blocks); the REPLAY side of the
//! chain walk is pinned by the synthetic production round trips in
//! `recovery.rs`, and the full real-image replay proof is the P7a-6 guest
//! interop gate.

